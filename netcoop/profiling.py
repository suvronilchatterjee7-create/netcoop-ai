"""Schema-agnostic profiling of generator output (Phase 0, task 4).

Reads every CSV / JSON / JSONL file under a directory without assuming any field
names, and writes a Markdown field inventory: types, null rates, numeric
distributions and example values. The profile drives the canonical schema.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

SUPPORTED_SUFFIXES = (".csv", ".json", ".jsonl")


def read_any(path: Path) -> pd.DataFrame:
    """Load a tabular or JSON file into a flat DataFrame."""
    suffix = path.suffix.lower()
    if suffix == ".csv":
        return pd.read_csv(path)
    if suffix == ".jsonl":
        rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]
        return pd.json_normalize(rows)
    if suffix == ".json":
        data: Any = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(data, dict):
            # Expand the first list-valued key if present, otherwise a single record.
            lists = {k: v for k, v in data.items() if isinstance(v, list)}
            if lists:
                return pd.concat(
                    [pd.json_normalize(v).assign(_section=k) for k, v in lists.items()],
                    ignore_index=True,
                )
            return pd.json_normalize(data)
        return pd.json_normalize(data)
    raise ValueError(f"unsupported file type: {path}")


def profile_frame(df: pd.DataFrame, max_examples: int) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for col in df.columns:
        s = df[col]
        entry: dict[str, Any] = {
            "field": str(col),
            "dtype": str(s.dtype),
            "null_rate": float(s.isna().mean()) if len(s) else 0.0,
            "n_unique": int(s.nunique(dropna=True)),
            "examples": [str(v) for v in s.dropna().unique()[:max_examples]],
        }
        if pd.api.types.is_numeric_dtype(s) and s.notna().any():
            q = s.quantile([0.0, 0.05, 0.5, 0.95, 1.0])
            entry["quantiles"] = {f"p{int(k * 100)}": float(v) for k, v in q.items()}
        out.append(entry)
    return out


def profile_directory(root: Path, max_examples: int) -> dict[str, list[dict[str, Any]]]:
    """Profile files grouped by file name (same-named files are concatenated)."""
    groups: dict[str, list[pd.DataFrame]] = {}
    for path in sorted(root.rglob("*")):
        if path.suffix.lower() in SUPPORTED_SUFFIXES and path.name != "meta.json":
            groups.setdefault(path.name, []).append(read_any(path))
    return {
        name: profile_frame(pd.concat(frames, ignore_index=True), max_examples)
        for name, frames in groups.items()
    }


def render_markdown(profile: dict[str, list[dict[str, Any]]], root: Path) -> str:
    lines = [
        "# Data profile",
        "",
        f"Auto-generated by `netcoop profile` from `{root.as_posix()}`. "
        "Do not edit by hand; add interpretation in the Notes section below.",
        "",
    ]
    for name, fields in profile.items():
        lines += [
            f"## `{name}`",
            "",
            "| field | dtype | null rate | unique | p5 / p50 / p95 | examples |",
            "|---|---|---|---|---|---|",
        ]
        for f in fields:
            q = f.get("quantiles")
            qs = f"{q['p5']:.4g} / {q['p50']:.4g} / {q['p95']:.4g}" if q else ""
            ex = ", ".join(f["examples"]).replace("|", "\\|")
            cells = [
                f"`{f['field']}`",
                f["dtype"],
                f"{f['null_rate']:.2%}",
                str(f["n_unique"]),
                qs,
                ex,
            ]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    lines += [
        "## Notes",
        "",
        "_Units, topology representation and dialect observations go here._",
        "",
    ]
    return "\n".join(lines)
