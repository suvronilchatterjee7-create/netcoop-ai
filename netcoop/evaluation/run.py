"""`netcoop eval`: full evaluation on the fresh test suite -> docs/EVALUATION.md.

1. Generate the test suite (config/evaluation.yaml ``test_suite.seeds``, the full sweep grid)
   if missing. These seeds were never used in development.
2. Full system on every test run: accuracy, precision of claims, macro-F1, confusion matrix,
   localisation, abstention precision and recall, calibration; slices by missing rate, noise,
   intensity and family.
3. Ablations on every ``ablation_stride``-th run: without courtroom, without corroboration,
   without the connectivity agent, each specialist alone.
4. Robustness curve: accuracy vs number of stacked interop mutations.
5. Unseen fault types: the ambiguity suite (hardware failure, device overload).
"""

from __future__ import annotations

import json
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from netcoop.agents.registry import registered
from netcoop.config import get_value, load_config
from netcoop.courtroom.evaluate import generate_suite
from netcoop.evaluation.harness import FULL, ablations, run_jobs, runs_under
from netcoop.evaluation.metrics import ABSTAIN, slices, summary
from netcoop.generation import run_sweep

REPO = Path(__file__).resolve().parents[2]
TEST_ROOT = REPO / "data" / "test"
REPORT = REPO / "docs" / "EVALUATION.md"
RECORDS = REPO / "runs" / "eval"


def ensure_test_suite(root: Path = TEST_ROOT) -> list[Path]:
    runs = runs_under(root)
    if not runs:
        run_sweep(root, seeds=list(get_value(load_config("evaluation"), "test_suite.seeds")))
        runs = runs_under(root)
    return runs


def evaluate_all(root: Path = TEST_ROOT, quick: bool = False) -> dict[str, Any]:
    ecfg = load_config("evaluation")
    workers = int(get_value(load_config("correlation_method"), "fitting.workers"))
    bins = int(get_value(load_config("correlation_method"), "calibration.ece_bins"))
    stride = int(get_value(ecfg, "test_suite.ablation_stride"))
    n_rob = int(get_value(ecfg, "robustness.runs"))
    levels = list(get_value(ecfg, "robustness.mutation_levels"))
    runs = ensure_test_suite(root)
    if quick:
        runs = runs[::stride]
    t0 = time.time()

    main = run_jobs([{"run": str(r), "config": FULL} for r in runs], workers)
    sub = runs[::stride] if not quick else runs[::2]
    specialists = sorted(registered())
    ablation_recs = {}
    for cfg in ablations(specialists):
        if cfg is FULL:
            names = {r.name for r in sub}
            ablation_recs[cfg["name"]] = [r for r in main if r["run"] in names]
        else:
            ablation_recs[cfg["name"]] = run_jobs(
                [{"run": str(r), "config": cfg} for r in sub], workers
            )
    rob_runs = runs[:: max(1, len(runs) // n_rob)][:n_rob]
    robust = run_jobs(
        [{"run": str(r), "config": FULL, "mutations": k} for k in levels for r in rob_runs], workers
    )
    unseen = run_jobs([{"run": str(r), "config": FULL} for r in generate_suite()], workers)

    RECORDS.mkdir(parents=True, exist_ok=True)
    (RECORDS / "records.json").write_text(
        json.dumps(
            {"main": main, "ablations": ablation_recs, "robustness": robust, "unseen": unseen}
        ),
        encoding="utf-8",
    )
    result = {
        "main": summary(main, bins),
        "slices": {k: slices(main, k) for k in ("family", "missing_rate", "noise", "intensity")},
        "ablations": {k: summary(v, bins) for k, v in ablation_recs.items()},
        "robustness": slices(robust, "mutations"),
        "unseen": summary(unseen, bins),
        "unseen_slices": slices(unseen, "family"),
        "n_runs": len(runs),
        "n_ablation": len(sub),
        "n_robust": len(rob_runs),
        "seconds": round(time.time() - t0, 1),
        "quick": quick,
    }
    REPORT.write_text(render(result), encoding="utf-8")
    return result


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{x:.1%}"


def render(r: dict[str, Any]) -> str:
    m = r["main"]
    cal = m["calibration"]
    seeds = get_value(load_config("evaluation"), "test_suite.seeds")
    lines = [
        "# Evaluation",
        "",
        f"Generated by `netcoop eval` on {datetime.now(UTC):%Y-%m-%d} "
        f"({'QUICK subsample' if r['quick'] else 'full run'}, {r['seconds']} s). Test suite: "
        f"**{r['n_runs']} fresh "
        f"runs, seeds {seeds}**, never used for calibration, fitting or development (D-042). "
        "Metric definitions "
        "at the end.",
        "",
        "## Headline (full system)",
        "",
        "| metric | value |",
        "|---|---|",
        f"| root-cause accuracy (correct / all runs) | **{_pct(m['accuracy'])}** |",
        "| precision of claims (correct / diagnoses + no-fault claims) | "
        f"**{_pct(m['claim_precision'])}** "
        f"({m['wrong']} wrong of {m['claims']}) |",
        f"| abstention rate | {_pct(m['abstain_rate'])} |",
        f"| macro-F1 over root-cause labels | {m['macro_f1']:.3f} |",
        f"| localisation precision / recall (affected devices, correct-type claims) | "
        f"{_pct(m['localisation_precision'])} / {_pct(m['localisation_recall'])} |",
        f"| root localisation (claimed root is a true location, correct-type claims) | "
        f"{_pct(m['root_localisation'])} |",
        f"| right fault type at a wrong location | {m['right_type_wrong_location']} |",
        "| abstention precision (abstained where the best guess was wrong) | "
        f"{_pct(m['abstention_precision'])} |",
        "| abstention recall (wrong best guesses that were withheld) | "
        f"{_pct(m['abstention_recall'])} |",
        f"| candidate calibration: Brier / ECE ({cal['n']} candidates) | {cal['brier']:.4f} / "
        f"{cal['ece']:.4f} |",
        f"| courtroom invoked | {m['courtroom_invoked']} runs |",
        "",
        "## Per root cause",
        "",
        "| root cause | support | precision | recall | F1 |",
        "|---|---|---|---|---|",
    ]
    for lab, v in sorted(m["per_label"].items()):
        lines.append(
            f"| {lab} | {v['support']} | {_pct(v['precision'])} | {_pct(v['recall'])} | "
            f"{v['f1']:.3f} |"
        )
    preds = sorted({p for row in m["confusion"].values() for p in row} - {ABSTAIN}) + [ABSTAIN]
    lines += [
        "",
        "## Confusion matrix (rows: truth, columns: prediction)",
        "",
        "| truth \\ predicted | " + " | ".join(preds) + " |",
        "|---" * (len(preds) + 1) + "|",
    ]
    for t, row in sorted(m["confusion"].items()):
        lines.append(f"| {t} | " + " | ".join(str(row.get(p, 0)) for p in preds) + " |")
    lines += ["", "## Robustness", ""]
    titles = {
        "missing_rate": "missing-data rate",
        "noise": "noise level",
        "intensity": "fault intensity",
        "family": "scenario family (interop = foreign dialect)",
    }
    for key in ("missing_rate", "noise", "intensity", "family"):
        lines += [
            f"By {titles[key]}:",
            "",
            f"| {titles[key]} | runs | accuracy | precision of claims | abstained |",
            "|---|---|---|---|---|",
        ]
        for k, v in r["slices"][key].items():
            lines.append(
                f"| {k} | {v['n']} | {_pct(v['accuracy'])} | {_pct(v['precision'])} | "
                f"{_pct(v['abstain'])} |"
            )
        lines.append("")
    lines += [
        f"By number of stacked interop mutations ({r['n_robust']} runs per level, "
        "netcoop/mutation.py):",
        "",
        "| mutations | runs | accuracy | precision of claims | abstained |",
        "|---|---|---|---|---|",
    ]
    for k, v in r["robustness"].items():
        lines.append(
            f"| {k} | {v['n']} | {_pct(v['accuracy'])} | {_pct(v['precision'])} | "
            f"{_pct(v['abstain'])} |"
        )
    lines += [
        "",
        f"## Ablations ({r['n_ablation']} test runs, every "
        f"{get_value(load_config('evaluation'), 'test_suite.ablation_stride')}th)",
        "",
        "| configuration | accuracy | precision of claims | wrong claims | abstained | macro-F1 |",
        "|---|---|---|---|---|---|",
    ]
    for name, v in r["ablations"].items():
        lines.append(
            f"| {name} | {_pct(v['accuracy'])} | {_pct(v['claim_precision'])} | {v['wrong']} | "
            f"{_pct(v['abstain_rate'])} | {v['macro_f1']:.3f} |"
        )
    u = r["unseen"]
    lines += [
        "",
        "## Fault types never seen true in training (ambiguity suite, fresh seeds 100-109)",
        "",
        f"{u['n']} runs: accuracy {_pct(u['accuracy'])}, precision of claims "
        f"{_pct(u['claim_precision'])} "
        f"({u['wrong']} wrong), abstained {_pct(u['abstain_rate'])}; courtroom invoked "
        f"{u['courtroom_invoked']} "
        "times. See COURTROOM_RESULTS.md for the with/without-courtroom comparison.",
        "",
        "| family | runs | accuracy | precision of claims | abstained |",
        "|---|---|---|---|---|",
    ]
    for k, v in r["unseen_slices"].items():
        lines.append(
            f"| {k} | {v['n']} | {_pct(v['accuracy'])} | {_pct(v['precision'])} | "
            f"{_pct(v['abstain'])} |"
        )
    lines += [
        "",
        "## Definitions",
        "",
        "- **Label:** the scenario family of the ground-truth root cause, from the generator's "
        "own parameters. For "
        "`interop_failure` runs it is the underlying network state, so they count by what is "
        "really wrong.",
        "- **Correct:** the claimed fault maps to that family **and** the claimed root is a true "
        "location; for "
        "normal runs, `no_fault_detected`. Any other diagnosis or no-fault claim is **wrong**. "
        "`insufficient_evidence` is an **abstention** (never correct, never wrong).",
        "- **Macro-F1:** per-label precision is computed over claims, and recall over all runs of "
        "that label "
        "(abstentions count as misses); the mean is unweighted.",
        "- **Localisation:** *root localisation* is the share of right-type claims whose root is "
        "a true location. "
        "*Affected-set* precision and recall compare `affected_devices` with the generator's "
        "ground truth "
        "(|affected ∩ true| / |affected| and / |true|). The report deliberately lists every place "
        "where users feel "
        "the fault (probe vantage points, service names), while the generator lists only the "
        "faulty elements, "
        "so the affected-set precision understates localisation by design.",
        "- **Abstention precision / recall:** the 'best guess' is the correlator's top candidate "
        "(or 'normal' "
        "when there is none). An abstention is justified if that guess was wrong. Recall is the "
        "share of wrong "
        "best guesses that were withheld.",
        "- **Calibration:** every ranked candidate's calibrated confidence against whether it is "
        "the true "
        "fault at a true location.",
        "",
    ]
    return "\n".join(lines)
