"""`netcoop calibrate`: derive normal-operation baselines from data (Part C1.2).

Only runs labelled ``normal`` from the **training** seeds are used (the held-out seeds stay
untouched for evaluation). Every run goes through the real Translator, so baselines are in
canonical units whatever the source dialect. For each (metric, entity type), and for each
(metric, entity category) as a fallback, the pooled samples give median, MAD and the
percentile band. For enum metrics the distribution of the per-series abnormal fraction is
used instead. The result is written to config/baselines.yaml with a generated rationale and
source on every entry, so it satisfies the same justification rule as hand-written config.
"""

from __future__ import annotations

import json
import math
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from statistics import median
from typing import Any

import yaml

from netcoop.config import CONFIG_DIR, get_value, load_config
from netcoop.detection import Detector, quantile
from netcoop.generation import DEFAULT_OUT, META_FILE
from netcoop.protocol.vocabulary import get_vocabulary
from netcoop.translator.translator import Translator

BASELINES = CONFIG_DIR / "baselines.yaml"


def seed_split() -> tuple[list[int], list[int]]:
    """(train, holdout) seeds from config/generation.yaml."""
    cfg = load_config("generation")
    seeds = sorted(get_value(cfg, "sweep.seeds"))
    n_hold = max(1, round(len(seeds) * float(get_value(cfg, "split.holdout_fraction"))))
    return seeds[:-n_hold], seeds[-n_hold:]


def _runs(root: Path, family: str, seeds: set[int]) -> list[Path]:
    out = []
    for d in sorted((root / family).iterdir()) if (root / family).is_dir() else []:
        meta = d / META_FILE
        if (
            meta.is_file()
            and json.loads(meta.read_text(encoding="utf-8"))["ground_truth"]["seed"] in seeds
        ):
            out.append(d)
    return out


def calibrate(
    root: Path = DEFAULT_OUT, out: Path = BASELINES, limit: int | None = None
) -> dict[str, Any]:
    vocab = get_vocabulary()
    cfg = load_config("generation")
    normal_family = get_value(cfg, "scenario_families")[0]
    train, _ = seed_split()
    runs = _runs(root, normal_family, set(train))[:limit]
    if not runs:
        raise ValueError(
            f"no '{normal_family}' runs for training seeds {train} under {root}; "
            "run `netcoop generate`"
        )
    detector = Detector()
    q = float(get_value(load_config("detection"), "significance.band_quantile"))
    samples: dict[tuple[str, str], list[float]] = defaultdict(list)
    translator = Translator()
    for run in runs:
        for o in translator.translate(run, "calibration").observations:
            mdef = vocab.metrics[o.metric]
            keys = (o.entity.entity_type, f"category:{vocab.category_of(o.entity.entity_type)}")
            if mdef.kind == "enum":
                healthy = detector.healthy.get(o.metric, set())
                recent = detector.recent([p.v for p in o.points])
                vals = [sum(1 for v in recent if v not in healthy) / len(recent)]
            else:
                vals = [float(p.v) for p in o.points]
            for k in keys:
                samples[(o.metric, k)] += vals

    when = datetime.now(UTC).strftime("%Y-%m-%d")
    entries: dict[str, dict[str, Any]] = defaultdict(dict)
    for (metric, key), vals in sorted(samples.items()):
        vals.sort()
        med = median(vals)
        mad = median(abs(v - med) for v in vals)
        unit = (
            "ratio (abnormal fraction)"
            if vocab.metrics[metric].kind == "enum"
            else vocab.metrics[metric].unit
        )
        entries[metric][key] = {
            "value": {
                "median": _r(med),
                "mad": _r(mad),
                "p_low": _r(quantile(vals, 1 - q)),
                "p_high": _r(quantile(vals, q)),
                "n": len(vals),
            },
            "unit": unit,
            "rationale": (
                f"Normal-operation distribution of {metric} for {key.replace('category:', 'any ')} "
                f"entities; p_low/p_high are the {1 - q:.3%}/{q:.1%} quantiles "
                "used as the abnormal band."
            ),
            "source": (
                f"derived empirically via `netcoop calibrate` on {len(runs)} "
                f"'{normal_family}' runs, "
                f"training seeds {train}, {when}"
            ),
        }
    doc = {
        "description": (
            "GENERATED by `netcoop calibrate` - do not edit by hand. "
            "Normal-operation baselines per "
            "(metric, entity type) with an entity-category fallback. Re-run after changing the "
            "generator or the Translator."
        ),
        "baselines": dict(entries),
    }
    out.write_text(yaml.safe_dump(doc, sort_keys=True, width=110), encoding="utf-8")
    return doc


def _r(x: float) -> float:
    return float(f"{x:.6g}") if math.isfinite(x) else x
